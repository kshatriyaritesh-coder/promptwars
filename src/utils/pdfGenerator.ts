import { jsPDF } from 'jspdf';
import { DailySmogPlan, UserHousehold, AirQualityData } from '../types';

export function exportPlanAsPdf(
  plan: DailySmogPlan,
  household: UserHousehold,
  aqiData: AirQualityData,
  language: 'en' | 'hi'
) {
  const doc = new jsPDF();
  const isHi = language === 'hi';

  doc.setFillColor(30, 41, 59);
  doc.rect(0, 0, 210, 38, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(20);
  doc.setFont('helvetica', 'bold');
  doc.text('SaansSaathi | Today\'s Family Smog Plan', 14, 18);

  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(203, 213, 225);
  doc.text(`${household.headName}'s Household · ${household.city} · ${plan.date}`, 14, 28);
  doc.text(`Nearest Station: ${aqiData.stationName}`, 14, 34);

  let y = 48;
  doc.setFillColor(241, 245, 249);
  doc.roundedRect(14, y, 182, 28, 3, 3, 'F');

  doc.setTextColor(15, 23, 42);
  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  doc.text(`Air Quality Index: ${aqiData.aqi} - ${aqiData.cpcbCategory}`, 20, y + 11);

  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(71, 85, 105);
  doc.text(`Dominant Pollutant: ${aqiData.dominantPollutant} (${aqiData.pollutants.pm25.value} ug/m3) | Weather: ${aqiData.weather.condition}`, 20, y + 20);

  y += 38;
  doc.setFontSize(13);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(15, 23, 42);
  doc.text('Key Daily Action Windows & Guidelines', 14, y);

  y += 8;
  doc.setFontSize(10);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(22, 101, 52);
  doc.text('Best Outdoor Window:', 14, y);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(51, 65, 85);
  doc.text(isHi ? plan.bestOutdoorWindowHi : plan.bestOutdoorWindow, 56, y);

  y += 8;
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(185, 28, 28);
  doc.text('Avoid Outdoors:', 14, y);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(51, 65, 85);
  doc.text(isHi ? plan.worstOutdoorWindowHi : plan.worstOutdoorWindow, 56, y);

  y += 8;
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(30, 41, 59);
  doc.text('Mask Standard:', 14, y);
  doc.setFont('helvetica', 'normal');
  doc.text(isHi ? plan.maskRecommendationHi : plan.maskRecommendation, 56, y);

  y += 8;
  doc.setFont('helvetica', 'bold');
  doc.text('Home & Ventilation:', 14, y);
  doc.setFont('helvetica', 'normal');
  const splitVent = doc.splitTextToSize(isHi ? plan.ventilationTimingHi : plan.ventilationTiming, 140);
  doc.text(splitVent, 56, y);
  y += splitVent.length * 5;

  y += 4;
  doc.setFont('helvetica', 'bold');
  doc.text('Low-Emission Win:', 14, y);
  doc.setFont('helvetica', 'normal');
  const splitWin = doc.splitTextToSize(isHi ? plan.lowEmissionTipHi : plan.lowEmissionTip, 140);
  doc.text(splitWin, 56, y);
  y += splitWin.length * 5 + 4;

  y += 6;
  doc.setFontSize(13);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(15, 23, 42);
  doc.text('Personalized Family Member Action Plan', 14, y);

  y += 6;
  plan.memberAssessments.forEach((mem) => {
    if (y > 265) {
      doc.addPage();
      y = 20;
    }

    doc.setFillColor(248, 250, 252);
    doc.roundedRect(14, y, 182, 22, 2, 2, 'F');

    doc.setFontSize(11);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(15, 23, 42);
    doc.text(`${mem.memberName} (${mem.age} yrs, ${mem.condition}) - Risk: ${mem.riskLevel}`, 18, y + 7);

    doc.setFontSize(9);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(71, 85, 105);
    const actionText = `${isHi ? mem.recommendations.outdoorActivityHi : mem.recommendations.outdoorActivity} | Mask: ${mem.recommendations.maskRequired}`;
    const splitAction = doc.splitTextToSize(actionText, 174);
    doc.text(splitAction, 18, y + 14);

    y += 26;
  });

  doc.setFontSize(8);
  doc.setTextColor(148, 163, 184);
  doc.text('Generated by SaansSaathi (BreatheEasy). Grounded in CPCB, WHO, ICMR guidelines. Non-medical advisory.', 14, 288);

  doc.save(`SaansSaathi_Smog_Plan_${household.city.replace(/\s+/g, '_')}_${new Date().toISOString().slice(0, 10)}.pdf`);
}
